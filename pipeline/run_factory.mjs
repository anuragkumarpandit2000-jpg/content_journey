import { execSync } from 'child_process';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import { createNextVideoFolder } from './1_create_video_folder.mjs';
import { buildTypographyData } from './3_build_typography_data.mjs';
import { renderReel } from './4_render_video.mjs';
import { uploadToInstagram } from './5_instagram_uploader.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = process.env.CONTENT_DIR || path.resolve(__dirname, '..');
const TEMPLATE_DIR = path.join(ROOT_DIR, 'video#5');

function resolvePythonBinary() {
  if (process.env.PYTHON_BIN) return process.env.PYTHON_BIN;
  const pgPython = 'C:/Program Files/PostgreSQL/18/pgAdmin 4/python/python.exe';
  if (process.platform === 'win32' && fs.existsSync(pgPython)) {
    return pgPython;
  }
  return 'python';
}

const PYTHON_BIN = resolvePythonBinary();

async function runAutonomousPipeline() {
  console.log('====================================================');
  console.log('🤖 STARTING AUTONOMOUS REEL FACTORY PIPELINE');
  console.log('====================================================\n');

  // Step 1: Detect and create next video#n folder
  const { folderName, targetDir } = createNextVideoFolder(ROOT_DIR, TEMPLATE_DIR);
  console.log(`\n>>> Step 1 Complete: Created ${folderName} at ${targetDir}`);

  // Step 2: Generate Voiceover & Words Timeline
  console.log(`\n>>> Step 2: Generating Neural Audio & Words Timeline via Edge-TTS...`);
  const audioScriptPath = path.join(__dirname, '2_generate_meta_audio.py');
  execSync(`"${PYTHON_BIN}" "${audioScriptPath}" "${targetDir}"`, {
    stdio: 'inherit',
  });

  // Step 3: Build Kinetic Typography Data & Three.js Theme Cues
  console.log(`\n>>> Step 3: Building Typography Data & Syncing Root Composition...`);
  buildTypographyData(targetDir);

  // Step 4: Render Master Video via Remotion CLI
  console.log(`\n>>> Step 4: Rendering Master Kinetic Typography 60FPS Video...`);
  const finalVideo = renderReel(targetDir);

  // Step 5: Instagram Deployment
  console.log(`\n>>> Step 5: Preparing Instagram Publishing...`);
  const caption = `Day 1 of letting an AI agent run this entire Instagram account autonomously! 🤖🔥
No human touched this video:
✅ Script written by AI
✅ Voice generated by Neural TTS
✅ 3D Three.js kinetic typography rendered via code
✅ Uploaded automatically from the cloud while my laptop is off!

Want the complete free source code and step-by-step pipeline?
Comment "AI CODE" and I will DM you the entire zero-cost blueprint! 🚀`;

  const hashtags = `#ai #automation #coding #remotion #threejs #techhacks #aitools #programming #developer #reelsindia`;
  await uploadToInstagram(finalVideo, caption, hashtags);

  console.log('\n====================================================');
  console.log(`🎉 AUTONOMOUS PIPELINE COMPLETED FOR ${folderName}!`);
  console.log(`Video Output: ${finalVideo}`);
  console.log('====================================================');
}

runAutonomousPipeline().catch((err) => {
  console.error('[FATAL PIPELINE ERROR]', err);
  process.exit(1);
});
